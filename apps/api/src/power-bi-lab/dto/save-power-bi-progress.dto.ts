import {
  IsIn,
  IsISO8601,
  IsNotEmpty,
  IsObject,
  IsOptional,
  IsString,
  ValidateNested,
} from 'class-validator';

import {
  Type,
} from 'class-transformer';

import {
  PowerBIWorkspaceDto,
} from './check-power-bi.dto.js';

/* =========================================================
   POWER BI WORKSPACE TAB
========================================================= */

export type PowerBIProgressWorkspaceTab =
  | 'data'
  | 'transform'
  | 'model'
  | 'dax'
  | 'report';

/* =========================================================
   SAVE POWER BI PROGRESS DTO

   Used when the learner clicks:

   Save Progress

   This does NOT:

   - calculate the final score
   - mark the attempt as completed
   - create a final submission

   It stores the learner's current Power BI workspace so
   the learner can continue later.
========================================================= */

export class SavePowerBIProgressDto {
  /* =======================================================
     PROBLEM SLUG

     Identifies the Power BI problem whose progress is
     being saved.

     Example:

     power-bi-import-sales-data
  ======================================================= */

  @IsString()
  @IsNotEmpty()
  problemSlug!: string;

  /* =======================================================
     WORKSPACE STATE

     Complete current learner workspace.

     Current workspace fields may include:

     - selectedDatasetId
     - loadedDatasetId
     - fileName
     - tableName
     - headers
     - rowCount
     - hasData
     - datasets
     - tables
     - transforms
     - relationships
     - measures
     - visuals
     - filters

     IMPORTANT:

     Save Progress stores the learner's actual state.

     It must NOT contain hidden validation rules or
     expected answers.
  ======================================================= */

  @IsObject()
  @ValidateNested()
  @Type(
    () => PowerBIWorkspaceDto,
  )
  workspace!: PowerBIWorkspaceDto;

  /* =======================================================
     ACTIVE WORKSPACE TAB

     Used to restore the learner to the same workspace
     section when progress is resumed.

     Supported values:

     data
     transform
     model
     dax
     report
  ======================================================= */

  @IsOptional()
  @IsString()
  @IsIn([
    'data',
    'transform',
    'model',
    'dax',
    'report',
  ])
  activeTab?: PowerBIProgressWorkspaceTab;

  /* =======================================================
     CLIENT SAVE TIMESTAMP

     Optional timestamp generated by the frontend.

     This value is informational only.

     The backend must generate its own authoritative
     savedAt / updatedAt timestamp.
  ======================================================= */

  @IsOptional()
  @IsString()
  @IsISO8601()
  clientSavedAt?: string;
}